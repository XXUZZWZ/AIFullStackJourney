/**
 * 以 nums = [1,3,-1,-3,5,3,6,7], k = 3 为例
 *
 * i=0: nums[0]=1
 *   队列: [0]  (对应值: [1])
 *   窗口: [1] (未满)
 *
 * i=1: nums[1]=3
 *   3 > 1, 移除0
 *   队列: [1]  (对应值: [3])
 *   窗口: [1,3] (未满)
 *
 * i=2: nums[2]=-1
 *   -1 < 3, 加入队列
 *   队列: [1,2]  (对应值: [3,-1])
 *   窗口: [1,3,-1] (满了) => 最大值 = 3 ✓
 *
 * i=3: nums[3]=-3
 *   队头1 在窗口内 [1,3]
 *   -3 < -1, 加入队列
 *   队列: [1,2,3]  (对应值: [3,-1,-3])
 *   窗口: [3,-1,-3] => 最大值 = 3 ✓
 *
 * i=4: nums[4]=5
 *   队头1 < 2 (窗口起始), 移除
 *   5 > -1, 移除2
 *   5 > -3, 移除3
 *   队列: [4]  (对应值: [5])
 *   窗口: [-1,-3,5] => 最大值 = 5 ✓
 *
 * i=5: nums[5]=3
 *   队头4 在窗口内 [3,5]
 *   3 < 5, 加入队列
 *   队列: [4,5]  (对应值: [5,3])
 *   窗口: [-3,5,3] => 最大值 = 5 ✓
 *
 * i=6: nums[6]=6
 *   队头4 在窗口内 [4,6]
 *   6 > 3, 移除5
 *   6 > 5, 移除4
 *   队列: [6]  (对应值: [6])
 *   窗口: [5,3,6] => 最大值 = 6 ✓
 *
 * i=7: nums[7]=7
 *   队头6 在窗口内 [5,7]
 *   7 > 6, 移除6
 *   队列: [7]  (对应值: [7])
 *   窗口: [3,6,7] => 最大值 = 7 ✓
 *
 * 结果: [3,3,5,5,6,7]
 */

