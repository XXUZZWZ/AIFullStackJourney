/**
 * 时间复杂度分析：
 * - 单调队列：O(n)
 *   每个元素最多入队一次、出队一次，所以总操作次数是 O(n)
 *
 * - 暴力解法：O(n*k)
 *   n-k+1 个窗口，每个窗口遍历 k 个元素
 *
 * 空间复杂度分析：
 * - 单调队列：O(k) - 队列最多存储 k 个元素
 * - 暴力解法：O(1) - 不考虑结果数组
 */

// ==================== 关键点总结 ====================
/**
 * 1. 为什么用单调队列？
 *    - 窗口滑动时需要快速获取最大值
 *    - 需要快速删除过期元素
 *    - 小于当前值的元素没有价值
 *
 * 2. 为什么存下标而不是值？
 *    - 需要判断元素是否在窗口内（通过下标判断）
 *    - 可以通过下标快速获取值
 *
 * 3. 单调递减的含义？
 *    - 队头到队尾，对应的值递减
 *    - 保证队头是最大值
 *    - 较小的值可能成为后续窗口的最大值（当大值移出窗口时）
 *
 * 4. 何时记录答案？
 *    - 当 i >= k-1 时，窗口已经形成
 *    - 此时队头就是窗口最大值
 */
