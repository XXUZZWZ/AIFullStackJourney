/**
 * 239. 滑动窗口最大值
 *
 * 核心思路：使用单调递减队列
 *
 * 为什么需要单调队列？
 * - 如果窗口内有两个数 a 和 b，且 a < b 并且 a 在 b 的左边
 * - 那么 a 永远不可能成为最大值（b 更大且更靠后）
 * - 所以我们只需要保留"可能成为最大值"的元素
 *
 * 单调队列的性质：
 * 1. 队列中存储数组下标（不是值）
 * 2. 队列中下标对应的值严格单调递减
 * 3. 队头元素就是当前窗口的最大值
 */

/**
 * 方法一：单调队列（最优解）
 * 时间复杂度：O(n) - 每个元素最多入队出队各一次
 * 空间复杂度：O(k) - 队列最多存储k个元素
 *
 * @param {number[]} nums
 * @param {number} k
 * @return {number[]}
 */
var maxSlidingWindow = function (nums, k) {
    const n = nums.length;
    const result = [];
    const deque = []; // 双端队列，存储数组下标

    for (let i = 0; i < n; i++) {
        // 1. 移除队头过期的元素（不在当前窗口内）
        // 当前窗口范围：[i - k + 1, i]
        while (deque.length > 0 && deque[0] < i - k + 1) {
            deque.shift(); // 移除队头
        }

        // 2. 维护单调递减性：移除队尾所有比当前元素小的元素
        // 因为当前元素更大且更靠后，前面小的元素不可能成为最大值
        while (deque.length > 0 && nums[deque[deque.length - 1]] < nums[i]) {
            deque.pop(); // 移除队尾
        }

        // 3. 将当前元素下标加入队列
        deque.push(i);

        // 4. 当窗口形成后（i >= k - 1），记录最大值
        // 队头元素就是当前窗口的最大值
        if (i >= k - 1) {
            result.push(nums[deque[0]]);
        }
    }

    return result;
};

/**
 * 方法二：暴力解法（用于理解问题）
 * 时间复杂度：O(n*k) - 每个窗口遍历k个元素
 * 空间复杂度：O(1) - 不考虑结果数组
 *
 * 注意：数据量大时会超时
 */
var maxSlidingWindowBrute = function (nums, k) {
    const n = nums.length;
    const result = [];

    // 遍历每个窗口的起始位置
    for (let i = 0; i <= n - k; i++) {
        let max = nums[i];
        // 遍历窗口内的每个元素，找最大值
        for (let j = i; j < i + k; j++) {
            max = Math.max(max, nums[j]);
        }
        result.push(max);
    }

    return result;
};

